-- BRD §13–16: Client billing, invoice line details, workflow logs, payment bank fields

ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS contact_person VARCHAR(150) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS invoice_email_recipients TEXT NULL,
  ADD COLUMN IF NOT EXISTS tax_preference VARCHAR(20) NULL DEFAULT 'AUTO';

ALTER TABLE invoices
  MODIFY COLUMN status ENUM(
    'DRAFT','APPROVED','SENT','PARTIAL','PAID','CANCELLED'
  ) NOT NULL DEFAULT 'DRAFT';

ALTER TABLE invoices
  ADD COLUMN IF NOT EXISTS service_description VARCHAR(255) NULL DEFAULT 'Transportation of Goods by Road',
  ADD COLUMN IF NOT EXISTS hsn_sac VARCHAR(20) NULL DEFAULT '996791',
  ADD COLUMN IF NOT EXISTS payment_terms VARCHAR(100) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS approved_at DATETIME NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS approved_by BIGINT UNSIGNED NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS pdf_generated_at DATETIME NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS email_sent_at DATETIME NULL DEFAULT NULL;

ALTER TABLE invoice_items
  ADD COLUMN IF NOT EXISTS consignor_name VARCHAR(200) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS consignor_invoice_no VARCHAR(100) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS consignor_invoice_date DATE NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS from_location VARCHAR(200) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS destination VARCHAR(200) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS vehicle_type VARCHAR(100) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS vehicle_number VARCHAR(50) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS gr_lr_number VARCHAR(100) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS reporting_date DATE NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS delivery_date DATE NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS quantity DECIMAL(12,3) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS quantity_unit VARCHAR(30) NULL DEFAULT NULL;

ALTER TABLE invoice_payments
  ADD COLUMN IF NOT EXISTS bank_name VARCHAR(150) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS bank_account VARCHAR(100) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS remarks VARCHAR(500) NULL DEFAULT NULL;

CREATE TABLE IF NOT EXISTS invoice_delivery_logs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  company_id BIGINT UNSIGNED NOT NULL,
  invoice_id BIGINT UNSIGNED NOT NULL,
  action_type ENUM('PDF_GENERATED','EMAIL_SENT') NOT NULL,
  recipient VARCHAR(255) NULL DEFAULT NULL,
  details TEXT NULL,
  created_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_invoice_delivery_company (company_id),
  KEY idx_invoice_delivery_invoice (invoice_id)
);
