ALTER TABLE bilties
  ADD COLUMN IF NOT EXISTS bilty_date DATE NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS copy_type VARCHAR(30) NULL DEFAULT 'CONSIGNOR',
  ADD COLUMN IF NOT EXISTS consignor_address VARCHAR(255) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS consignee_address VARCHAR(255) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS truck_no VARCHAR(50) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS vehicle_id BIGINT UNSIGNED NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS charged_weight_kg DECIMAL(12,2) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS packages_label VARCHAR(50) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS rate_remark VARCHAR(150) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS invoice_no VARCHAR(100) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS invoice_value VARCHAR(150) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS payment_mode VARCHAR(30) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS gst_payer VARCHAR(40) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS delivery_type VARCHAR(30) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS insurance_at_risk VARCHAR(30) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS insurance_company VARCHAR(150) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS insurance_policy_no VARCHAR(100) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS insurance_date DATE NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS insurance_amount DECIMAL(12,2) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS total_amount DECIMAL(12,2) NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS terms_notes TEXT NULL;

CREATE TABLE IF NOT EXISTS bilty_charges (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  company_id BIGINT UNSIGNED NOT NULL,
  bilty_id BIGINT UNSIGNED NOT NULL,
  charge_type VARCHAR(40) NOT NULL,
  amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_bilty_charges_company_bilty (company_id, bilty_id),
  KEY idx_bilty_charges_type (charge_type)
);
